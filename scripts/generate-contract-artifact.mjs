import { readFile, writeFile } from "node:fs/promises";

const source = new URL("../build/contracts/SponsorshipEscrow.json", import.meta.url);
const destination = new URL(
  "../src/contracts/SponsorshipEscrowArtifact.ts",
  import.meta.url,
);
const artifact = JSON.parse(await readFile(source, "utf8"));
if (!Array.isArray(artifact.abi) || !/^0x[0-9a-f]+$/i.test(artifact.bytecode)) {
  throw new Error("Truffle artifact is missing ABI or deployment bytecode");
}

const output = `// Generated by scripts/generate-contract-artifact.mjs. Do not edit by hand.\n` +
  `export const sponsorshipEscrowArtifact = ${JSON.stringify({
    abi: artifact.abi,
    bytecode: artifact.bytecode,
  })} as const;\n\n` +
  `export const sponsorshipEscrowAbi = sponsorshipEscrowArtifact.abi;\n` +
  `export const sponsorshipEscrowBytecode = sponsorshipEscrowArtifact.bytecode;\n`;

await writeFile(destination, output);
